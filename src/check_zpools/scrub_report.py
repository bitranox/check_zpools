"""Reporting for a scrub cycle: human-readable text, JSON, and email.

Purpose
-------
Turn a :class:`~check_zpools.models.ScrubCycleResult` into the three shapes a
scrub run has to be consumed in: a console summary, a machine-readable JSON
document, and a summary email.

Contents
--------
* :func:`format_scrub_summary_text` - console/email body
* :func:`format_scrub_summary_json` - machine-readable form
* :func:`build_scrub_subject` - email subject line
* :func:`send_scrub_summary` - deliver the summary by email

System Role
-----------
Presentation layer for the scrub command. Holds no policy: whether a pool is
a problem is decided by the domain model, not here.
"""

from __future__ import annotations

import json
import logging
import socket
from typing import TYPE_CHECKING, Any

from . import __init__conf__
from .formatters import format_bytes_human
from .mail import send_email

if TYPE_CHECKING:
    from datetime import timedelta

    from .mail import EmailConfig
    from .models import PoolScrubOutcome, ScrubCycleResult

logger = logging.getLogger(__name__)

_SECONDS_PER_MINUTE = 60
_SECONDS_PER_HOUR = 3600


def format_duration(duration: timedelta | None) -> str:
    """Format a duration as `HH:MM:SS`, or `-` when unknown.

    Why
        Scrub durations run to many hours, so the natural unit is the same
        `HH:MM:SS` that `zpool status` itself prints.

    Examples
    --------
    >>> from datetime import timedelta
    >>> format_duration(timedelta(seconds=262))
    '00:04:22'
    >>> format_duration(timedelta(hours=7, minutes=30, seconds=5))
    '07:30:05'
    >>> format_duration(None)
    '-'
    """
    if duration is None:
        return "-"
    total_seconds = int(duration.total_seconds())
    hours, remainder = divmod(total_seconds, _SECONDS_PER_HOUR)
    minutes, seconds = divmod(remainder, _SECONDS_PER_MINUTE)
    return f"{hours:02d}:{minutes:02d}:{seconds:02d}"


def build_scrub_subject(result: ScrubCycleResult, *, subject_prefix: str, hostname: str | None = None) -> str:
    """Build the summary email subject.

    Why
        The subject must answer "do I need to open this?" on a phone screen.

    Examples
    --------
    >>> from datetime import datetime, timezone
    >>> from check_zpools.models import ScrubCycleResult
    >>> now = datetime.now(timezone.utc)
    >>> result = ScrubCycleResult(now, now, [], waited=True, dry_run=False)
    >>> build_scrub_subject(result, subject_prefix="[ZFS]", hostname="pbs")
    '[ZFS] [pbs] ZFS scrub completed'
    """
    host = hostname if hostname is not None else socket.gethostname()
    state = "problems detected" if result.has_problems() else "completed"
    if result.dry_run:
        state = "dry run"
    return f"{subject_prefix} [{host}] ZFS scrub {state}"


def format_scrub_summary_text(result: ScrubCycleResult, *, hostname: str | None = None) -> str:
    """Render the scrub cycle as a plain-text report.

    Why
        Used both as the email body and as the console output, so a mail and a
        terminal never disagree about what happened.

    Examples
    --------
    >>> from datetime import datetime, timezone
    >>> from check_zpools.models import ScrubCycleResult
    >>> now = datetime.now(timezone.utc)
    >>> report = format_scrub_summary_text(
    ...     ScrubCycleResult(now, now, [], waited=True, dry_run=False), hostname="pbs"
    ... )
    >>> "ZFS Scrub Report" in report
    True
    """
    host = hostname if hostname is not None else socket.gethostname()
    lines = [
        "ZFS Scrub Report",
        "=" * 60,
        f"Host: {host}",
        f"Started: {result.started_at.isoformat(timespec='seconds')}",
        f"Finished: {result.finished_at.isoformat(timespec='seconds')}",
        f"Total duration: {format_duration(result.duration)}",
        f"Waited for completion: {'yes' if result.waited else 'no'}",
    ]
    if result.dry_run:
        lines.append("Dry run: nothing was started")
    lines.append("")

    if not result.outcomes:
        lines.append("No pools were processed.")
    for outcome in result.outcomes:
        lines.extend(_format_outcome(outcome))
        lines.append("")

    lines.extend(
        [
            "-" * 60,
            f"Generated by {__init__conf__.title} v{__init__conf__.version}",
        ]
    )
    return "\n".join(lines)


def _format_outcome(outcome: PoolScrubOutcome) -> list[str]:
    """Render one pool's outcome as report lines."""
    marker = "PROBLEM" if outcome.is_problem else "OK"
    lines = [
        f"[{marker}] Pool: {outcome.pool_name}",
        f"  Action: {outcome.action.value}",
    ]
    if outcome.reason:
        lines.append(f"  Reason: {outcome.reason}")

    scan = outcome.final_scan
    if scan is None:
        lines.append("  Scan: no scan information available")
        return lines

    lines.extend(
        [
            f"  Scan: {scan.function.value} {scan.state.value}",
            f"  Progress: {scan.progress_percent:.1f}%",
            f"  Examined: {format_bytes_human(scan.examined_bytes)} of {format_bytes_human(scan.to_examine_bytes)}",
            f"  Duration: {format_duration(scan.duration)}",
            f"  Errors: {scan.errors}",
        ]
    )
    if scan.start_time is not None:
        lines.append(f"  Started: {scan.start_time.isoformat(timespec='seconds')}")
    if scan.end_time is not None:
        lines.append(f"  Ended: {scan.end_time.isoformat(timespec='seconds')}")
    return lines


def format_scrub_summary_json(result: ScrubCycleResult, *, hostname: str | None = None) -> str:
    """Render the scrub cycle as JSON.

    Why
        Lets the command feed a monitoring system without screen-scraping.

    Examples
    --------
    >>> import json
    >>> from datetime import datetime, timezone
    >>> from check_zpools.models import ScrubCycleResult
    >>> now = datetime.now(timezone.utc)
    >>> payload = json.loads(
    ...     format_scrub_summary_json(
    ...         ScrubCycleResult(now, now, [], waited=False, dry_run=True), hostname="pbs"
    ...     )
    ... )
    >>> payload["hostname"], payload["dry_run"], payload["pools"]
    ('pbs', True, [])
    """
    host = hostname if hostname is not None else socket.gethostname()
    payload: dict[str, Any] = {
        "hostname": host,
        "started_at": result.started_at.isoformat(),
        "finished_at": result.finished_at.isoformat(),
        "duration_seconds": result.duration.total_seconds(),
        "waited": result.waited,
        "dry_run": result.dry_run,
        "has_problems": result.has_problems(),
        "pools": [_outcome_as_dict(outcome) for outcome in result.outcomes],
    }
    return json.dumps(payload, indent=2)


def _outcome_as_dict(outcome: PoolScrubOutcome) -> dict[str, Any]:
    """Convert one outcome to a JSON-ready dict."""
    scan = outcome.final_scan
    return {
        "pool": outcome.pool_name,
        "action": outcome.action.value,
        "reason": outcome.reason,
        "is_problem": outcome.is_problem,
        "scan": None
        if scan is None
        else {
            "function": scan.function.value,
            "state": scan.state.value,
            "start_time": None if scan.start_time is None else scan.start_time.isoformat(),
            "end_time": None if scan.end_time is None else scan.end_time.isoformat(),
            "progress_percent": round(scan.progress_percent, 2),
            "examined_bytes": scan.examined_bytes,
            "to_examine_bytes": scan.to_examine_bytes,
            "issued_bytes": scan.issued_bytes,
            "duration_seconds": None if scan.duration is None else scan.duration.total_seconds(),
            "errors": scan.errors,
        },
    }


def send_scrub_summary(
    result: ScrubCycleResult,
    *,
    email_config: EmailConfig,
    recipients: list[str],
    subject_prefix: str,
    hostname: str | None = None,
) -> bool:
    """Email the scrub summary.

    Why
        A scrub runs unattended from a timer; the report has to come to the
        operator rather than wait in a log nobody reads.

    Parameters
    ----------
    result:
        The finished scrub cycle.
    email_config:
        SMTP settings.
    recipients:
        Where to send the summary.
    subject_prefix:
        Prefix applied to the subject, from the alerting configuration.
    hostname:
        Override the detected hostname (used by tests).

    Returns
    -------
    bool:
        True when the mail was handed to the SMTP layer, False when there was
        nobody to send it to.

    Raises
    ------
    RuntimeError:
        When SMTP delivery fails.
    """
    if not recipients:
        logger.warning("No scrub summary recipients configured, skipping email")
        return False

    subject = build_scrub_subject(result, subject_prefix=subject_prefix, hostname=hostname)
    body = format_scrub_summary_text(result, hostname=hostname)
    logger.info("Sending scrub summary", extra={"recipients": recipients, "subject": subject})
    return send_email(config=email_config, recipients=recipients, subject=subject, body=body)


